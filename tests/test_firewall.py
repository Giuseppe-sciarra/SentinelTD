"""Siti dietro un firewall o un antibot (2.48.0): firma delle richieste, riconoscimento della
pagina di blocco, intestazioni extra del sito e token che resta sul dominio del sito.

Caso reale (24 ottobre 2026): un sito su SiteGround, col suo antibot, smette di rispondere a
Sentinel. Al posto del JSON del connettore arriva un HTTP 202 con un rimando a
/.well-known/sgcaptcha, mentre il sito ai browser risponde normalmente.
"""
import unittest
from types import SimpleNamespace
from unittest.mock import AsyncMock, patch

import test_screenshot_schedule  # noqa: F401  (percorso di app e variabili d'ambiente di prova)
import httpx

from app import connectors, site_http
from test_connector_down import OK_PAYLOAD, unrestricted_slot

SG_CHALLENGE = ('<html><head><link rel="icon" href="data:;"><meta http-equiv="refresh" '
                'content="0;/.well-known/sgcaptcha/?r=%2Fwp-json%2Ftdpanopticon%2Fv1%2Fstatus&y=ipr:1.2.3.4">'
                '</head><body></body></html>')
CF_CHALLENGE = ('<!DOCTYPE html><html><head><title>Just a moment...</title></head><body>'
                '<script src="/cdn-cgi/challenge-platform/h/b/orchestrate/chl_page/v1"></script></body></html>')


def html(code, body, **headers):
    return httpx.Response(code, text=body, headers={"content-type": "text/html; charset=UTF-8", **headers})


class FirewallRecognitionTests(unittest.TestCase):
    def test_siteground_antibot_202(self):
        self.assertEqual(site_http.firewall_block(html(202, SG_CHALLENGE)), "SiteGround")

    def test_cloudflare_challenge_by_header_or_page(self):
        self.assertEqual(site_http.firewall_block(html(403, CF_CHALLENGE, **{"cf-mitigated": "challenge"})), "Cloudflare")
        self.assertEqual(site_http.firewall_block(html(403, CF_CHALLENGE, server="cloudflare")), "Cloudflare")
        self.assertEqual(site_http.firewall_block(html(403, "error code: 1020", server="cloudflare")), "Cloudflare")

    def test_other_firewalls(self):
        self.assertEqual(site_http.firewall_block(html(403, "<h1>Sucuri WebSite Firewall - Access Denied</h1>")), "Sucuri")
        self.assertEqual(site_http.firewall_block(html(403, "<p>Access denied by Imunify360 bot-protection</p>")), "Imunify360")
        self.assertEqual(site_http.firewall_block(html(503, "Your access to this site has been limited by Wordfence")), "Wordfence")
        self.assertEqual(site_http.firewall_block(html(406, "<h1>Not Acceptable!</h1> generated by Mod_Security")), "ModSecurity")
        self.assertEqual(site_http.firewall_block(html(403, "Please complete the CAPTCHA")), "WAF/antibot")

    def test_cms_answers_are_never_a_firewall(self):
        # 403 di WordPress (JSON): resta "accesso rifiutato" con le spiegazioni di sempre
        self.assertEqual(site_http.firewall_block(httpx.Response(403, json={"code": "rest_forbidden"})), "")
        self.assertEqual(site_http.firewall_block(httpx.Response(200, json=OK_PAYLOAD)), "")
        # pagina qualsiasi: decide la controprova sulla home, come prima
        self.assertEqual(site_http.firewall_block(html(200, "<html>home</html>")), "")
        self.assertEqual(site_http.firewall_block(html(404, "<h1>Pagina non trovata</h1>")), "")
        # Cloudflare davanti a un sito che risponde: niente blocco senza la pagina di verifica
        self.assertEqual(site_http.firewall_block(html(404, "<h1>404</h1>", server="cloudflare")), "")


class FirewallFetchTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.site = SimpleNamespace(id=72, name="Prima Piuma", cms="wp", url="https://www.example.test", token="t",
                                    extra_headers="")
        self.responses, self.requests = [], []

        async def handler(request):
            self.requests.append(request)
            return self.responses.pop(0)
        self.client = httpx.AsyncClient(transport=httpx.MockTransport(handler), follow_redirects=True,
                                        event_hooks={"request": [connectors._strip_token_offsite]})
        self.patches = [patch.object(connectors, "status_slot", unrestricted_slot),
                        patch.object(connectors, "status_client", AsyncMock(return_value=self.client)),
                        patch("app.eventlog.record_now", AsyncMock())]
        for p in self.patches:
            p.start()
        connectors._WP_REST_STYLE.clear()

    async def asyncTearDown(self):
        for p in reversed(self.patches):
            p.stop()
        await self.client.aclose()
        connectors._WP_REST_STYLE.clear()

    async def test_siteground_block_is_a_connector_problem_without_second_route(self):
        self.responses = [html(202, SG_CHALLENGE)]
        with self.assertRaises(connectors.FirewallBlocked) as cm:
            await connectors.fetch_status(self.site)
        self.assertEqual(len(self.requests), 1)          # stesso firewall anche sull'altra forma REST
        self.assertFalse(cm.exception.ambiguous)          # -> _mark_connector, mai "sito offline"
        # connettore che non sa ancora chiamare Sentinel: si dice come farlo passare da solo (2.49.0)
        self.assertEqual(str(cm.exception), "bloccato da SiteGround davanti al sito (HTTP 202): installa a mano "
                         "sul sito il connettore WordPress 2.41.0 o successivo scaricato da Impostazioni → Connettori "
                         "e Sentinel passerà da solo")

    async def test_requests_carry_sentinel_signature_and_extra_headers(self):
        self.site.extra_headers = "X-Sentinel-Pass: segreto\nCF-Access-Client-Id: abc.access"
        self.responses = [httpx.Response(200, json=OK_PAYLOAD)]
        await connectors.fetch_status(self.site)
        sent = self.requests[0].headers
        self.assertTrue(sent["user-agent"].startswith("Mozilla/5.0 (compatible; SentinelTD/"))
        self.assertNotIn("python-httpx", sent["user-agent"])
        self.assertEqual(sent["x-sentinel-pass"], "segreto")
        self.assertEqual(sent["cf-access-client-id"], "abc.access")
        self.assertEqual(sent["x-sentinel-token"], "t")

    async def test_token_survives_www_redirect_but_not_another_domain(self):
        self.site.url = "https://example.test"
        self.site.extra_headers = "X-Sentinel-Pass: segreto"
        self.responses = [
            httpx.Response(301, headers={"location": "https://www.example.test/wp-json/tdpanopticon/v1/status"}),
            httpx.Response(200, json=OK_PAYLOAD),
        ]
        await connectors.fetch_status(self.site)
        self.assertEqual(self.requests[1].url.host, "www.example.test")
        self.assertEqual(self.requests[1].headers.get("x-sentinel-token"), "t")

        connectors._WP_REST_STYLE.clear()
        self.requests.clear()
        self.responses = [
            httpx.Response(302, headers={"location": "https://parcheggio.test/"}),
            httpx.Response(200, json=OK_PAYLOAD),
        ]
        await connectors.fetch_status(self.site)
        moved = self.requests[1].headers
        self.assertIsNone(moved.get("x-sentinel-token"))
        self.assertIsNone(moved.get("authorization"))
        self.assertIsNone(moved.get("x-sentinel-pass"))


class ExtraHeadersTests(unittest.TestCase):
    def test_normalized_and_validated(self):
        text = "  X-Sentinel-Pass :  abc  \n\n# commento\nCF-Access-Client-Secret: s3cr3t"
        self.assertEqual(site_http.normalize_extra_headers(text),
                         "X-Sentinel-Pass: abc\nCF-Access-Client-Secret: s3cr3t")
        self.assertEqual(site_http.normalize_extra_headers(""), "")

    def test_rejects_what_sentinel_manages_or_breaks_requests(self):
        for bad in ("Authorization: x", "X-Sentinel-Token: x", "Host: altro.it", "Cookie: a=b",
                    "senza due punti", "Nome con spazi: x", "X-A: 1\nx-a: 2", "X-Vuoto:"):
            with self.assertRaises(ValueError, msg=bad):
                site_http.parse_extra_headers(bad)
        with self.assertRaises(ValueError):
            site_http.parse_extra_headers("\n".join(f"X-H{i}: v" for i in range(11)))

    def test_user_agent_can_be_overridden_per_site(self):
        site = SimpleNamespace(extra_headers="User-Agent: RegolaCloudflare/1")
        self.assertEqual(site_http.site_headers(site, {"Accept": "application/json"})["User-Agent"], "RegolaCloudflare/1")
        self.assertNotIn("user-agent", site_http.secret_header_names(site))

    def test_same_site_host(self):
        self.assertTrue(site_http.same_site_host("www.sito.it", "sito.it"))
        self.assertTrue(site_http.same_site_host("SITO.it", "www.sito.it"))
        self.assertFalse(site_http.same_site_host("sito.it.evil.test", "sito.it"))
        self.assertFalse(site_http.same_site_host("shop.sito.it", "sito.it"))
        self.assertFalse(site_http.same_site_host("", ""))


